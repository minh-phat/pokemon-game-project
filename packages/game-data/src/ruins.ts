import type { ArenaDefinition, ArenaObstacle } from '@arena/shared-types';

/** Pixel coordinates refer to the user's untouched 1942 × 810 PNG. */
export const RUINS_ART = {
  url: '/assets/ruins-map.png',
  width: 1942,
  height: 810,
  scale: 2400 / 1942,
};
export const ruinsPoint = (x: number, y: number) => ({
  x: x * RUINS_ART.scale,
  depth: y * RUINS_ART.scale - 520,
});
function obstacle(
  id: string,
  kind: ArenaObstacle['kind'],
  left: number,
  top: number,
  right: number,
  bottom: number,
  height: number,
): ArenaObstacle {
  return {
    id,
    kind,
    ...ruinsPoint((left + right) / 2, (top + bottom) / 2),
    width: (right - left) * RUINS_ART.scale,
    length: (bottom - top) * RUINS_ART.scale,
    height: height * RUINS_ART.scale,
  };
}
